#!/usr/bin/env python3
"""Generate .github/workflows/portable.yml from editions/portable/.github/workflows/xp.yml.

The portable C edition (XP exe, Linux GTK3/GTK4, Android) is imported from boochain/lan-secure-messenger-xp
with git subtree (tools/sync-from-xp.sh).  Its own workflow stays untouched inside the subtree (GitHub only runs
workflows from the repo root), and this script rewrites it into a reusable workflow that runs in editions/portable:
triggers -> workflow_call, default working-directory, artifact paths and step working-directories prefixed.
"""
import re, sys
P = "editions/portable"
SRC = f"{P}/.github/workflows/xp.yml"
DST = ".github/workflows/portable.yml"

s = open(SRC, encoding="utf-8").read()
s = re.sub(r"working-directory: (?!/)(\S+)", lambda m: f"working-directory: {P}/{m.group(1)}", s)
s = re.sub(r"\Aname: [^\n]*\non:\n(?:  [^\n]*\n)+", f"""# GENERATED by tools/gen-portable-workflow.py from {SRC} -- do not edit by hand.
name: portable (XP exe, Linux GTK3/GTK4, Android)
on:
  workflow_call:
  workflow_dispatch:
defaults:
  run:
    working-directory: {P}
""", s, count=1)
s = s.replace('ln -sfn "$GITHUB_WORKSPACE" /src', f'ln -sfn "$GITHUB_WORKSPACE/{P}" /src')

def one(v):
    return v if v.startswith(("/", "${{", "|")) else f"{P}/{v}"
def fix(m):
    v = m.group(2)
    if v.startswith('"'):
        return m.group(1) + '"' + "\\n".join(one(x) for x in v.strip('"').split("\\n")) + '"'
    return m.group(1) + one(v)
s = re.sub(r"(path: )(\"[^\"]*\"|[^,}\s]+)", fix, s)

out, blk = [], None
for l in s.split("\n"):
    ind = len(l) - len(l.lstrip())
    if blk is not None:
        if l.strip() and ind > blk:
            st = l.lstrip(); out.append(" " * ind + one(st)); continue
        blk = None
    if re.match(r"\s+path: \|$", l):
        blk = ind
    out.append(l)
s = "\n".join(out)
# the emulator runner's script runs from its own working-directory input
s = re.sub(r"(\n(\s+)disable-animations: true\n)", lambda m: m.group(1) + f"{m.group(2)}working-directory: {P}\n", s)
# steps that run before actions/checkout cannot use editions/portable (it does not exist yet): run them from /
out, seen = [], True
for l in s.split("\n"):
    if re.match(r"  [a-z0-9-]+:$", l): seen = False          # new job
    if "actions/checkout@" in l: seen = True
    m = re.match(r"(\s+)- run: (.*)$", l)
    if not seen and m:
        out += [f"{m.group(1)}- working-directory: /", f"{m.group(1)}  run: {m.group(2)}"]; continue
    m = re.match(r"(\s+)- name: (.*)$", l)
    out.append(l)
    if not seen and m:
        out.append(f"{m.group(1)}  working-directory: /")
s = "\n".join(out)
open(DST, "w", encoding="utf-8").write(s)
print("wrote", DST)
