#!/usr/bin/env python3
"""Generate .github/workflows/portable.yml from editions/portable/.github/workflows/xp.yml.

The portable C edition (XP exe, Linux GTK3/GTK4, Android) is imported from boochain/lan-secure-messenger-xp
with git subtree (tools/sync-from-xp.sh).  Its own workflow stays untouched inside the subtree (GitHub only runs
workflows from the repo root), and this script rewrites it into a reusable workflow that runs in editions/portable:
triggers -> workflow_call, default working-directory, artifact paths and step working-directories prefixed.
"""
import re, sys
P = "editions/portable"
SRC = f"{P}/.github/workflows/xp.yml"
DST = ".github/workflows/portable.yml"

s = open(SRC, encoding="utf-8").read()
s = re.sub(r"working-directory: (?!/)(\S+)", lambda m: f"working-directory: {P}/{m.group(1)}", s)
s = re.sub(r"\Aname: [^\n]*\non:\n(?:  [^\n]*\n)+", f"""# GENERATED by tools/gen-portable-workflow.py from {SRC} -- do not edit by hand.
name: portable (XP exe, Linux GTK3/GTK4, Android)
on:
  workflow_call:
  workflow_dispatch:
defaults:
  run:
    working-directory: {P}
""", s, count=1)
s = s.replace('ln -sfn "$GITHUB_WORKSPACE" /src', f'ln -sfn "$GITHUB_WORKSPACE/{P}" /src')

def one(v):
    return v if v.startswith(("/", "${{", "|")) else f"{P}/{v}"
def fix(m):
    v = m.group(2)
    if v.startswith('"'):
        return m.group(1) + '"' + "\\n".join(one(x) for x in v.strip('"').split("\\n")) + '"'
    return m.group(1) + one(v)
s = re.sub(r"(path: )(\"[^\"]*\"|[^,}\s]+)", fix, s)

out, blk = [], None
for l in s.split("\n"):
    ind = len(l) - len(l.lstrip())
    if blk is not None:
        if l.strip() and ind > blk:
            st = l.lstrip(); out.append(" " * ind + one(st)); continue
        blk = None
    if re.match(r"\s+path: \|$", l):
        blk = ind
    out.append(l)
s = "\n".join(out)
# the emulator runner's script runs from its own working-directory input
s = re.sub(r"(\n(\s+)disable-animations: true\n)", lambda m: m.group(1) + f"{m.group(2)}working-directory: {P}\n", s)
# steps that run before actions/checkout cannot use editions/portable (it does not exist yet): run them from /
out, seen = [], True
for l in s.split("\n"):
    if re.match(r"  [a-z0-9-]+:$", l): seen = False          # new job
    if "actions/checkout@" in l: seen = True
    m = re.match(r"(\s+)- run: (.*)$", l)
    if not seen and m:
        out += [f"{m.group(1)}- working-directory: /", f"{m.group(1)}  run: {m.group(2)}"]; continue
    m = re.match(r"(\s+)- name: (.*)$", l)
    out.append(l)
    if not seen and m:
        out.append(f"{m.group(1)}  working-directory: /")
s = "\n".join(out)
# Unified repo: the cross-implementation matrix runs against the CURRENT Rust daemon (root workspace) -- the
# reference/v0.5 snapshot has no resume / relay, so the matrix's resume checks cannot pass against it. interop.py
# keeps testing the frozen v0.5 daemon (backward compatibility).
s = s.replace("(cd reference/v0.5 && cargo build --release -p lan-daemon -p lan-cli)",
              "(cd reference/v0.5 && cargo build --release -p lan-daemon -p lan-cli) && (cd $GITHUB_WORKSPACE && cargo build --release -p lan-daemon -p lan-cli)")
s = re.sub(r"(working-directory: editions/portable/reference/v0.5\n(\s+)run: cargo build --release -p lan-daemon -p lan-cli)",
           r"\1 && (cd $GITHUB_WORKSPACE && cargo build --release -p lan-daemon -p lan-cli)", s)
# Encrypted-backup interop (C core <-> current Rust lan-core, LSMBAK02); only meaningful in the unified repo.
_anchor = "      - name: Interop under wine (x86 exe <-> v0.5 lan-daemon, netns bridge)\n"
assert s.count(_anchor) == 1, "backup interop anchor"
s = s.replace(_anchor, """      - name: Backup interop (C core <-> Rust lan-core, LSMBAK02)
        run: |
          (cd $GITHUB_WORKSPACE && cargo build --release -p lan-core --example backup_tool)
          cc -Wall -Wno-misleading-indentation -Isrc -o /tmp/updcheck_test tests/updcheck_test.c && /tmp/updcheck_test
          cc -O1 -std=gnu99 -Isrc -Wno-unused-function -o /tmp/firewall_test tests/firewall_test.c src/core.c src/xcrypto.c src/third_party/monocypher.c src/third_party/monocypher-ed25519.c -lpthread && /tmp/firewall_test
          cc -O1 -std=gnu99 -Isrc -Wno-unused-function -o /tmp/trust_file_test tests/trust_file_test.c src/core.c src/xcrypto.c src/third_party/monocypher.c src/third_party/monocypher-ed25519.c -lpthread && /tmp/trust_file_test
          # live check against the real releases list with this build's version (VERSION, or the tag)
          V=$(cat ../../VERSION); [ "${{ github.ref_type }}" = tag ] && V=${GITHUB_REF_NAME#v}
          curl -fsSL -H 'User-Agent: lsm-ci' "https://api.github.com/repos/boochain/lan-secure-messenger/releases?per_page=10" -o /tmp/rel.json && /tmp/updcheck_test /tmp/rel.json "$V"
          python3 tests/backup_interop.py --cli build/linux/lanmsg-cli --rust-tool $GITHUB_WORKSPACE/target/release/examples/backup_tool
""" + _anchor)
s = "\n".join(l.replace("--no-resume-kinds rust ", "").replace("--rust-bin reference/v0.5/target/release", "--rust-bin $GITHUB_WORKSPACE/target/release") if "tests/matrix.py" in l else l
              for l in s.split("\n"))
open(DST, "w", encoding="utf-8").write(s)
print("wrote", DST)
